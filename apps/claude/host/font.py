# Characters that should render as an existing glyph rather than consume a slot
# of their own. Claude Code picks from a family of circles and asterisks
# depending on state, and any of them left uncovered falls back to a letter "o"
# or an "*", which is what was showing on the real machine.
ALIASES = {
    "●": "⏺",    # black circle -> the filled bullet
    "○": "◉",    # white circle -> the fisheye outline
    "⏹": "⏺",    # stop
    "•": "·",    # bullet -> middle dot
    "‣": "❯",    # triangular bullet
    "✻": "✳",    # teardrop asterisk -> the Claude asterisk
    "✶": "✳",
    "✷": "✳",
    "✴": "✳",    # eight-pointed
    "✽": "✳",
    "★": "✳", "☆": "✳",
    "→": "❯",    # arrows reuse the chevron
    "▸": "❯", "▶": "❯", "›": "❯",
    "↳": "⎿",    # down-then-right -> the result elbow
    "⌐": "─",
    "\ue0b0": "│",   # powerline separators are just dividers here
    "\ue0b1": "│",
    "\ue0b2": "│",
    "\ue0b3": "│",
}


def _rows(art: str):
    rows = [line.strip() for line in art.strip().splitlines()]
    if len(rows) != 8:
        raise ValueError(f"glyph must be 8 rows, got {len(rows)}")
    out = []
    for r in rows:
        if len(r) != 8:
            raise ValueError(f"glyph row must be 8 columns, got {len(r)!r}")
        out.append(sum(1 << (7 - i) for i, c in enumerate(r) if c != "."))
    return out


# char -> screen code, and screen code -> 8 byte bitmap
CODES = {}
BITMAPS = {}
if len(GLYPH_ART) > len(FREE_SLOTS):
    raise RuntimeError(
        f"{len(GLYPH_ART)} custom glyphs but only {len(FREE_SLOTS)} free slots")

for _i, (_ch, _art) in enumerate(GLYPH_ART.items()):
    _code = FREE_SLOTS[_i]
    CODES[_ch] = _code
    BITMAPS[_code] = _rows(_art)

LAST_SLOT = FREE_SLOTS[len(GLYPH_ART) - 1]

# Aliases resolve to an already-allocated glyph, or are dropped if their target
# is a plain PETSCII character that petscii.GLYPHS already handles.
for _alias, _target in ALIASES.items():
    if _target in CODES:
        CODES[_alias] = CODES[_target]


def definitions():
    """(code, 8-byte bitmap) pairs, ready for the wire."""
    return sorted(BITMAPS.items())


def render(ch: str) -> str:
    """Draw a glyph as art again, for eyeballing in a test."""
    code = CODES[ch]
    return "\n".join(
        "".join("#" if b & (1 << (7 - x)) else "." for x in range(8))
        for b in BITMAPS[code]
    )
