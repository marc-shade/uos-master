"""Custom glyphs uploaded into the C128's VDC character RAM.

The VDC keeps its character definitions in its own RAM, not in ROM, so the ones
Claude Code needs and PETSCII lacks can simply be drawn. The C128 KERNAL loads
512 definitions at the base in R28: the first 256 are the uppercase/graphics
set, the second 256 the lowercase set the bridge encodes to. Only unused slots
in that second bank are overwritten, so ordinary text keeps the authentic
Commodore letterforms.

Each glyph is an 8x8 bitmap written as art so it can be read and edited
directly. The VDC reserves 16 bytes per definition; rows 8-15 are not displayed
in an 8-pixel character box and are cleared.
"""

# Codes in the lowercase bank that the PETSCII table already claims for real
# glyphs. Redefining any of these would corrupt the Claude Code logo or the box
# drawing, so they are skipped. Kept here rather than imported from petscii to
# avoid a circular import; test_font_slots_are_free checks the two agree.
